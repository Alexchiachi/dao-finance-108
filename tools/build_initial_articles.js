躺在病床上的高智商工程師閉上眼睛，兩行眼淚無聲地滑落進枕頭裡。那一杯來自南投深山的冷茶，洗淨了一個月來資訊毒素對心智的侵蝕，也喚醒了一個人對生命本真的敬畏。

