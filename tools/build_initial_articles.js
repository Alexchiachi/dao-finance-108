阿銘顫抖著接過杯子，喝了一口。清冽、微苦，隨後是一股漫長而純淨的回甘，帶著南投清晨山林的草木芬香。那一瞬間，過去一個月來六塊螢幕裡閃爍的無數數字、警報、恐慌推播，突然像潮水一樣從他的大腦中退去。

